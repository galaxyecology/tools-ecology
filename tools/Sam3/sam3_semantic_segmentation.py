def convert_avi_to_mp4(directory_path, quality):
    """
    Convert AVI file to MP4.
    Parameters:
        quality : "copy"  = original resolution and quality (no re-encoding)
                  "2000k" = video bitrate 2000 kbps (480p~720p)
                  "4000k" = video bitrate 4000 kbps (1080p standard)
                  "8000k" = video bitrate 8000 kbps (1080p high quality)
    """
    print(f"Quality : {quality}")
    avi_file_path = glob.glob(os.path.join(directory_path, "*.avi"))[0]
    output_path = os.path.splitext(avi_file_path)[0]
    print(f"Converting: {avi_file_path} -> {output_path}.mp4")
    audio_args = "-an"  # remove audio
    if quality == "copy":
        video_args = (
            "-c:v libx264 -crf 18 -preset slow "
            "-profile:v high -pix_fmt yuv420p"
        )
    else:
        video_args = (
            f"-c:v libx264 -b:v {quality} "
            "-vprofile high -bf 0"  # re-encode with H.264
        )
    cmd = (
        f"ffmpeg -i '{avi_file_path}' "
        f"{video_args} "
        f"{audio_args} "
        f"'{output_path}.mp4'"
    )
    print(f"Command : {cmd}")
    os.popen(cmd)
    return True


def is_video(file_path: str) -> bool:
    """Check if a file is a video based on its extension."""
    return Path(file_path).suffix.lower() in VIDEO_EXTENSIONS


def compute_file_hash(filepath: Path) -> str:
    """Compute SHA256 hash of a file."""
    hasher = hashlib.sha256()
    with open(filepath, "rb") as f:
        # Read file in chunks to handle large files efficiently
        for chunk in iter(lambda: f.read(8192), b""):
            hasher.update(chunk)
    return hasher.hexdigest()


def validate_coco_format(annotation_file: Path) -> bool:
    """Validate COCO JSON format."""
    try:
        COCO(str(annotation_file))
        print(f"✓ COCO file is valid: {annotation_file}")
        return True
    except Exception as e:
        print(f"COCO format error: {e}")
        return False


def create_coco_categories(text_prompts: List[str]) -> List[Dict[str, Any]]:
    """
    Create COCO categories from text prompts.
    Returns: List of category dictionaries
    """
    return [
        {"id": i + 1, "name": label} for i, label in enumerate(text_prompts)
    ]


def create_coco_output(
    results: List[Any],
    text_prompts: List[str],
    metadata: Dict[str, Any],
    is_normalized: bool,
) -> Dict[str, Any]:
    """Convert SAM3 results to COCO format."""
    coco_output = {
        "info": metadata,
        "images": [],
        "annotations": [],
        "categories": create_coco_categories(text_prompts),
    }

    annotation_id = 1

    for image_idx, result in enumerate(results):
        if result.masks is None:
            continue

        height, width = result.orig_shape
        image_id = image_idx + 1
        filename = Path(result.path).name

        # Add image information
        coco_output["images"].append(
            {
                "id": image_id,
                "file_name": filename,
                "width": width,
                "height": height,
            }
        )

        polygons = result.masks.xyn if is_normalized else result.masks.xy
        boxes = result.boxes.xyxyn if is_normalized else result.boxes.xyxy
        track_ids = (
            result.boxes.id.int().tolist()
            if result.boxes.id is not None
            else [None] * len(result.boxes.cls)
        )

        for polygon, bbox, class_id, track_id in zip(
            polygons, boxes, result.boxes.cls, track_ids
        ):
            # Flatten polygon coordinates
            polygon_flat = polygon.flatten().tolist()

            # Extract bounding box coordinates (normalized)
            x1, y1, x2, y2 = bbox[:4].tolist()
            bbox_w = x2 - x1
            bbox_h = y2 - y1
            # Calculate area using contour
            area = float(cv2.contourArea(polygon.astype(np.float32)))

            coco_output["annotations"].append(
                {
                    "id": annotation_id,
                    "image_id": image_id,
                    "category_id": int(class_id) + 1,
                    "track_id": track_id,
                    "segmentation": [polygon_flat],
                    "area": area,
                    "bbox": [x1, y1, bbox_w, bbox_h],
                    "iscrowd": 0,
                }
            )
            annotation_id += 1

    return coco_output


def create_yolo_bbox_annotation(box: np.ndarray, class_id: int) -> str:
    """Create YOLO bounding box annotation line."""
    x1, y1, x2, y2 = box[:4].tolist()

    # Convert to YOLO format (center_x, center_y, width, height)
    x_center = (x1 + x2) / 2
    y_center = (y1 + y2) / 2
    bbox_width = x2 - x1
    bbox_height = y2 - y1

    return (
        f"{class_id} {x_center:.6f} "
        f"{y_center:.6f} {bbox_width:.6f} "
        f"{bbox_height:.6f}"
    )


def create_yolo_seg_annotation(polygon: np.ndarray, class_id: int) -> str:
    """Create YOLO segmentation annotation line."""
    # Flatten polygon coordinates
    flattened = [f"{coord:.6f}" for point in polygon for coord in point]
    return f"{class_id} " + " ".join(flattened)


def create_yolo_output(
    annotation_type: str,
    results: List[Any],
    output_dir: Path,
    is_normalized: bool,
) -> None:
    """Export annotations in YOLO format for images."""
    # Create subdirectories for images and labels
    images_dir = output_dir / "images"
    labels_dir = output_dir / "labels"
    images_dir.mkdir(exist_ok=True, parents=True)
    labels_dir.mkdir(exist_ok=True, parents=True)

    for result in results:
        # Generate output filename based on source image
        image_name = Path(result.path).stem

        # Copy image to images directory
        image_src = Path(result.path)
        image_dst = images_dir / f"{image_name}{image_src.suffix}"

        import shutil

        shutil.copy2(image_src, image_dst)

        # Create label file path
        output_path = labels_dir / f"{image_name}.txt"

        lines = []

        boxes = result.boxes.xyxyn if is_normalized else result.boxes.xyxy
        # Process each detection
        for i, (box, class_id) in enumerate(zip(boxes, result.boxes.cls)):
            class_id = int(class_id)

            if annotation_type == "bbox":
                line = create_yolo_bbox_annotation(box, class_id)
            else:  # segmentation
                masks = result.masks.xyn if is_normalized else result.masks.xy
                line = create_yolo_seg_annotation(masks[i], class_id)

            lines.append(line)

        # Write annotations to file
        with open(output_path, "w") as f:
            f.write("\n".join(lines))

    print(f"✓ Created {len(results)} images and labels in {output_dir}")


def create_coco_video_frames_output(
    results: List[Any],
    text_prompts: List[str],
    metadata: Dict[str, Any],
    is_normalized: bool,
    video_path: str,
    stride: int,
    outdir: Path,
) -> Dict[str, Any]:
    """Convert SAM3 video results to COCO format with one image entry
    per extracted frame."""
    frames_dir = outdir / "frames"
    frames_dir.mkdir(parents=True, exist_ok=True)

    coco_output = {
        "info": metadata,
        "images": [],
        "annotations": [],
        "categories": create_coco_categories(text_prompts),
    }

    cap = cv2.VideoCapture(video_path)
    if not cap.isOpened():
        raise RuntimeError(f"Failed to open video: {video_path}")

    video_name = Path(video_path).stem
    annotation_id = 1
    frame_idx = 1 if stride > 1 else 0
    saved_idx = 0

    print(
        f"Extracting frames and building per-frame COCO annotations "
        f"(stride={stride})..."
    )

    while cap.isOpened():
        ret, frame = cap.read()
        if not ret:
            break

        if frame_idx % stride == 0:
            if saved_idx >= len(results):
                print(f"Warning: No result available for frame {frame_idx}")
                break

            frame_name = f"{video_name}_frame_{frame_idx:06d}.jpg"
            frame_path = frames_dir / frame_name
            cv2.imwrite(str(frame_path), frame)

            result = results[saved_idx]
            image_id = saved_idx + 1
            height, width = result.orig_shape

            coco_output["images"].append(
                {
                    "id": image_id,
                    "file_name": frame_name,
                    "width": width,
                    "height": height,
                    "frame_index": frame_idx,
                }
            )

            if result.masks is not None:
                polygons = (
                    result.masks.xyn if is_normalized else result.masks.xy
                )
                boxes = (
                    result.boxes.xyxyn if is_normalized else result.boxes.xyxy
                )
                track_ids = (
                    result.boxes.id.int().tolist()
                    if result.boxes.id is not None
                    else [None] * len(result.boxes.cls)
                )

                for polygon, bbox, class_id, track_id in zip(
                    polygons, boxes, result.boxes.cls, track_ids
                ):
                    polygon_flat = polygon.flatten().tolist()
                    x1, y1, x2, y2 = bbox[:4].tolist()
                    bbox_w = x2 - x1
                    bbox_h = y2 - y1
                    area = float(cv2.contourArea(polygon.astype(np.float32)))

                    coco_output["annotations"].append(
                        {
                            "id": annotation_id,
                            "image_id": image_id,
                            "category_id": int(class_id) + 1,
                            "track_id": track_id,
                            "segmentation": [polygon_flat],
                            "area": area,
                            "bbox": [x1, y1, bbox_w, bbox_h],
                            "iscrowd": 0,
                        }
                    )
                    annotation_id += 1

            saved_idx += 1

            if saved_idx % 10 == 0:
                print(f"  Extracted {saved_idx} frames...")

        frame_idx += 1

    cap.release()
    print(f"✓ Extracted {saved_idx} frames to {frames_dir}")
    return coco_output


def create_yolo_video_output(
    annotation_type: str,
    results: List[Any],
    output_dir: Path,
    video_path: str,
    stride: int,
    is_normalized: bool,
) -> None:
    """Export annotations in YOLO format for videos with frame extraction."""
    # Create subdirectories for images and labels
    images_dir = output_dir / "images"
    labels_dir = output_dir / "labels"
    images_dir.mkdir(exist_ok=True, parents=True)
    labels_dir.mkdir(exist_ok=True, parents=True)

    # Open video file
    cap = cv2.VideoCapture(video_path)
    if not cap.isOpened():
        raise RuntimeError(f"Failed to open video: {video_path}")

    video_name = Path(video_path).stem

    # Initialize counters
    frame_idx = 1 if stride > 1 else 0
    saved_idx = 0

    print(f"Processing video frames (stride={stride})...")

    while cap.isOpened():
        ret, frame = cap.read()
        if not ret:
            break

        # Process only frames according to stride
        if frame_idx % stride == 0:
            frame_base = f"{video_name}_frame_{frame_idx:06d}"

            # Save frame as image
            img_path = images_dir / f"{frame_base}.jpg"
            cv2.imwrite(str(img_path), frame)

            # Create corresponding label file
            label_path = labels_dir / f"{frame_base}.txt"

            # Get prediction result for this frame
            if saved_idx >= len(results):
                print(f"Warning: No result available for frame {frame_idx}")
                break

            result = results[saved_idx]
            lines = []

            # Process detections if available
            boxes = result.boxes.xyxyn if is_normalized else result.boxes.xyxy
            for i, (box, class_id) in enumerate(zip(boxes, result.boxes.cls)):
                class_id = int(class_id)

                if annotation_type == "bbox":
                    line = create_yolo_bbox_annotation(box, class_id)
                else:  # segmentation
                    polygon = (
                        result.masks.xyn if is_normalized else result.masks.xy
                    )
                    line = create_yolo_seg_annotation(polygon, class_id)

                lines.append(line)

            # Write label file
            with open(label_path, "w") as f:
                f.write("\n".join(lines))

            saved_idx += 1

            if saved_idx % 10 == 0:
                print(f"  Processed {saved_idx} frames...")

        frame_idx += 1

    cap.release()
    print(f"✓ Created {saved_idx} frames and labels in {output_dir}")


def extract_video_frames(
    video_path: str,
    stride: int,
    results: List[Any],
    raw_dir: Path = None,
    annotated_dir: Path = None,
    show_bbox: bool = True,
) -> None:
    """Extract video frames as images, annotated and/or raw."""
    if raw_dir:
        raw_dir.mkdir(parents=True, exist_ok=True)
    if annotated_dir:
        annotated_dir.mkdir(parents=True, exist_ok=True)

    cap = cv2.VideoCapture(video_path)
    if not cap.isOpened():
        raise RuntimeError(f"Failed to open video: {video_path}")

    video_name = Path(video_path).stem
    frame_idx = 1 if stride > 1 else 0
    saved_idx = 0

    print(f"Extracting frames (stride={stride})...")

    while cap.isOpened():
        ret, frame = cap.read()
        if not ret:
            break

        if frame_idx % stride == 0:
            if saved_idx >= len(results):
                print(f"Warning: No result available for frame {frame_idx}")
                break

            frame_name = f"{video_name}_frame_{frame_idx:06d}.jpg"

            if raw_dir is not None:
                cv2.imwrite(str(raw_dir / frame_name), frame)

            if annotated_dir is not None:
                annotated_frame = results[saved_idx].plot(boxes=show_bbox)
                cv2.imwrite(str(annotated_dir / frame_name), annotated_frame)

            saved_idx += 1
            if saved_idx % 10 == 0:
                print(f"  Extracted {saved_idx} frames...")

        frame_idx += 1

    cap.release()
    print(f"✓ Extracted {saved_idx} frames")


def create_metadata(
    text_prompts: List[str], conf_threshold: float, model_path: str
) -> Dict[str, Any]:
    """Create metadata dictionary for COCO export."""
    model_path = Path(model_path)

    return {
        "description": "SAM3 semantic segmentation export",
        "model": "sam3.pt",
        "model_sha256": (
            compute_file_hash(model_path) if model_path.exists() else "N/A"
        ),
        "prompts": text_prompts,
        "confidence_threshold": conf_threshold,
        "ultralytics_version": ultralytics.__version__,
    }


# -------- Main --------


def main():

    # Parse the JSON parameter document written by Galaxy
    args = parse_arguments()
    config = load_config(args.config)
    tool_input = config.get("input") or {}

    is_normalized = as_bool(config.get("do_normalization"))
    show_bbox = as_bool(config.get("show_bbox"), default=True)

    # Parse text prompts
    text_prompts = [
        prompt.strip()
        for prompt in str(config.get("text_prompt") or "").split(",")
        if prompt.strip()
    ]
    print(f"\nClass prompts: {text_prompts}")

    model = args.model or config.get("sam3_models")
    conf = float(config.get("conf", DEFAULT_CONFIDENCE))
    imgsz = as_int(config.get("imgsz"), DEFAULT_IMGSZ)
    vid_stride = as_int(config.get("vid_stride"), DEFAULT_VID_STRIDE)
    quality = tool_input.get("quality", "copy")
    output_frames = tool_input.get("output_frames", "none")

    # Stage the input datasets, Galaxy provides a sanitised staging_path for
    # every dataset (see stage_input_datasets)
    stage_input_datasets(as_dataset_list(tool_input.get("source")))

    # Setup paths relative to the working directory
    folder = Path(INPUT_DIR).resolve()
    print(f"folder: {folder}")
    # Get all files in the data folder (iterdir also yields dot files, which
    # glob('*') would silently skip)
    file_paths = sorted(str(f) for f in folder.iterdir() if f.is_file())
    print(f"file_paths: {file_paths}")

    if not file_paths:
        print("Error: No input files were provided")
        return

    # Use folder path as source for Ultralytics
    source_path = str(folder)

    # Setup output directories
    outdir = Path(OUTPUT_DIR)
    outdir.mkdir(exist_ok=True, parents=True)

    outputs_annotated = outdir / "outputs_annotated"
    outputs_annotated.mkdir(parents=True, exist_ok=True)

    output_formats = as_list(tool_input.get("outputs_format"))
    # COCO annotations are always produced for videos (see the output filter)
    if is_video(file_paths[0]) and "coco" not in output_formats:
        output_formats.insert(0, "coco")
    print(f"Output formats: {output_formats}")

    # Configure predictor overrides
    overrides = {
        "conf": conf,
        "show_conf": True,
        "show_boxes": show_bbox,
        "task": "segment",
        "mode": "predict",
        "model": model,
        "half": False,
        "imgsz": imgsz,
        "save": True,
        "save_dir": str(outputs_annotated),
    }

    # Determine if input is video or image and initialize appropriate predictor
    if is_video(file_paths[0]):
        print("\nVideo input detected → using SAM3VideoSemanticPredictor")
        overrides["vid_stride"] = vid_stride
        predictor = SAM3VideoSemanticPredictor(overrides=overrides)

    else:
        print("\nImage input detected → using SAM3SemanticPredictor")
        predictor = SAM3SemanticPredictor(overrides=overrides)

    # Patch predictor to include custom class names
    original_postprocess = predictor.postprocess

    def patched_postprocess(preds, img, orig_imgs):
        """Patch postprocess to add custom class names to results."""
        results = original_postprocess(preds, img, orig_imgs)
        # Add class names to each result
        for r in results:
            r.names = {i: name for i, name in enumerate(text_prompts)}
        return results

    predictor.postprocess = patched_postprocess

    # Run predictions
    # print(f"\n Running prediction on {source_path}...")
    results = predictor(source=source_path, text=text_prompts, stream=False)
    if is_video(file_paths[0]):
        convert_avi_to_mp4(outputs_annotated, quality)

        if output_frames != "none":
            print(
                f"\n→ Extracting video frames "
                f"(mode: {output_frames})..."
            )
            raw_dir = (
                outdir / "frames_raw"
                if output_frames in ("raw", "both")
                else None
            )
            annotated_dir = (
                outdir / "frames_annotated"
                if output_frames in ("annotated", "both")
                else None
            )
            extract_video_frames(
                file_paths[0],
                vid_stride,
                results,
                raw_dir=raw_dir,
                annotated_dir=annotated_dir,
                show_bbox=show_bbox,
            )

    if not results:
        raise RuntimeError("SAM3 returned no results")

    print(f"✓ Processed {len(results)} result(s)")

    # Create metadata
    metadata = create_metadata(text_prompts, conf, model)

    # Export in requested formats
    print("\n" + "=" * 60)
    print("EXPORTING RESULTS")
    print("=" * 60)

    if "coco" in output_formats:
        print("\n→ Converting to COCO format...")

        if is_video(file_paths[0]):
            print("  Mode: per-frame (extracting individual frames)...")
            coco_output = create_coco_video_frames_output(
                results,
                text_prompts,
                metadata,
                is_normalized,
                file_paths[0],
                vid_stride,
                outdir,
            )
        else:
            coco_output = create_coco_output(
                results, text_prompts, metadata, is_normalized
            )

