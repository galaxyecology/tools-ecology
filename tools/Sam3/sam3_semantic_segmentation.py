def parse_arguments() -> argparse.Namespace:
    """Parse the command line.

    Galaxy renders the tool parameters with::

        <configfiles>
            <inputs name="inputs" filename="inputs.json"
                    data_style="staging_path_and_source_path"/>
        </configfiles>

    so this wrapper receives a single JSON document instead of a long list of
    command line options. Only the model path is passed separately, because a
    select fed from a data table is serialised with its value, not with its
    fields (see wrapped_json.py in Galaxy).
    """
    parser = argparse.ArgumentParser(
        description="SAM3 to COCO/YOLO exporter with semantic segmentation"
    )
    parser.add_argument(
        "config",
        type=str,
        help="JSON parameter file generated by Galaxy (inputs.json)",
    )
    parser.add_argument(
        "--model",
        type=str,
        default=None,
        help="path of the SAM3 weights (data table 'path' column)",
    )
    return parser.parse_args()


def load_config(config_path: str) -> Dict[str, Any]:
    """Load the JSON parameter document."""
    with open(config_path) as handle:
        return json.load(handle)


def as_bool(value: Any, default: bool = False) -> bool:
    """Normalise a Galaxy boolean, which is rendered as a JSON bool."""
    if value is None:
        return default
    if isinstance(value, bool):
        return value
    return str(value).strip().lower() in ("true", "1", "yes")


def as_int(value: Any, default: int) -> int:
    """Normalise a Galaxy integer or select value."""
    try:
        return int(str(value).strip())
    except (TypeError, ValueError):
        return default


def as_list(value: Any) -> List[str]:
    """Normalise a (multiple) select value to a list of strings.

    Tools with ``profile >= 20.05`` receive multiple selects as JSON arrays,
    older releases used comma separated strings, and an empty optional
    selection is either ``[]`` or the literal ``"None"``.
    """
    if value is None:
        return []
    if isinstance(value, str):
        value = value.split(",")
    return [
        str(item).strip()
        for item in value
        if str(item).strip() not in ("", "None")
    ]


def as_dataset_list(value: Any) -> List[Dict[str, Any]]:
    """Normalise the ``source`` input to a list of dataset dictionaries."""
    if not value:
        return []
    if isinstance(value, dict):
        return [value]
    return [dataset for dataset in value if dataset]


def stage_input_datasets(
    datasets: List[Dict[str, Any]], input_dir: str = INPUT_DIR
) -> List[Path]:
    """Symlink every input dataset into a single input directory.

    Galaxy computes a filesystem safe ``staging_path`` for each dataset
    (``filesystem_safe_string``: ``/`` replaced, leading dots stripped, length
    limited to 254 bytes, everything else kept verbatim) but does not create
    it, so the links are made here. Ultralytics derives the names of every
    output from the input file stem, so two datasets whose staging paths
    collide would silently overwrite each other's annotations - that is
    rejected instead of renamed, because a renamed file would also appear under
    a different name in the output collections.
    """
    directory = Path(input_dir)
    directory.mkdir(parents=True, exist_ok=True)

    by_name: Dict[str, str] = {}
    by_stem: Dict[str, str] = {}
    staged = []

    for dataset in datasets:
        source_path = dataset.get("source_path")
        if not source_path:
            continue
        name = Path(dataset.get("staging_path") or source_path).name
        # Galaxy stages an input as "<element identifier>.<ext>". For uploaded
        # files the identifier already ends with the extension (the dataset is
        # called "shrimp.png" and its ext is "png"), which would leave every
        # staged name - and every output derived from it - doubled.
        ext = dataset.get("ext")
        if ext:
            suffix = f".{ext}".lower()
            if name.lower().endswith(suffix + suffix):
                name = name[: -len(suffix)]
        identifier = str(dataset.get("element_identifier") or name)
        stem = Path(name).stem

        clash = by_name.get(name, by_stem.get(stem))
        if clash is not None:
            raise ValueError(
                "Input datasets "
                f"'{clash}' and '{identifier}' share the file name "
                f"'{stem}' (staged as '{name}'), so their output files would "
                "overwrite each other. Rename one of the datasets and run the "
                "tool again."
            )
        by_name[name] = identifier
        by_stem[stem] = identifier

        target = directory / name
        if target.is_symlink():
            # Re-run in a working directory that is still staged
            target.unlink()
        elif target.exists():
            raise ValueError(
                f"Cannot stage '{name}': {target} already exists and is not a "
                "link created by this tool."
            )
        os.symlink(os.path.abspath(source_path), target)
        staged.append(target)

    return staged


