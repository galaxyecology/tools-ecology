def convert_avi_to_mp4(directory_path, quality):
    """
    Transcode the annotated video ultralytics wrote (AVI/MJPG) into MP4.

    Galaxy discovers this directory as a collection, so exactly one annotated
    video has to survive: after a successful conversion the AVI is removed and
    the MP4 stays, after a failed one the error is logged and the AVI stays,
    because it is the only annotated video there is.

    Returns True when every AVI was converted and removed.

    Parameters:
        quality : "copy"  = original resolution and quality (no re-encoding)
                  "2000k" = video bitrate 2000 kbps (480p~720p)
                  "4000k" = video bitrate 4000 kbps (1080p standard)
                  "8000k" = video bitrate 8000 kbps (1080p high quality)
    """
    print(f"Quality : {quality}")
    directory = Path(directory_path)
    avi_files = sorted(directory.glob("*.avi"))
    if not avi_files:
        contents = ", ".join(sorted(p.name for p in directory.iterdir()))
        print(
            f"Error: no annotated .avi in '{directory}' "
            f"(contents: {contents or 'none'}), nothing to convert",
            file=sys.stderr,
        )
        return False

    if quality == "copy":
        video_args = [
            "-c:v", "libx264", "-crf", "18", "-preset", "slow",
            "-profile:v", "high", "-pix_fmt", "yuv420p",
        ]
    else:
        video_args = [
            "-c:v", "libx264", "-b:v", quality,
            "-vprofile", "high", "-bf", "0",
        ]

    converted = True
    for avi_file in avi_files:
        mp4_file = avi_file.with_suffix(".mp4")
        # -y overwrites a stale file, -nostdin keeps ffmpeg away from stdin
        argv = [
            "ffmpeg",
            "-nostdin",
            "-y",
            "-i",
            str(avi_file),
            *video_args,
            "-an",  # remove audio
            str(mp4_file),
        ]
        print(f"Converting: {avi_file} -> {mp4_file}")
        print("Command : " + " ".join(shlex.quote(arg) for arg in argv))
        try:
            completed = subprocess.run(
                argv, capture_output=True, text=True, errors="replace"
            )
        except FileNotFoundError:
            print(
                "Error: ffmpeg not found, keeping the annotated video "
                f"'{avi_file.name}'",
                file=sys.stderr,
            )
            return False
        if completed.returncode != 0:
            print(
                f"Error: ffmpeg failed with exit code {completed.returncode}, "
                f"keeping the annotated video '{avi_file.name}'",
                file=sys.stderr,
            )
            print(completed.stderr.strip(), file=sys.stderr)
            # ffmpeg leaves a truncated .mp4 behind, which Galaxy would
            # collect as a second (broken) annotated video
            mp4_file.unlink(missing_ok=True)
            converted = False
            continue
        size = mp4_file.stat().st_size
        if size == 0:
            print(
                "Error: ffmpeg produced an empty file, keeping the "
                f"annotated video '{avi_file.name}'",
                file=sys.stderr,
            )
            mp4_file.unlink(missing_ok=True)
            converted = False
            continue
        avi_file.unlink()
        print(f"Converted: {avi_file.name} -> {mp4_file.name} ({size} bytes)")

    return converted


def is_video(file_path: str) -> bool:
    """Check if a file is a video based on its extension."""
    return Path(file_path).suffix.lower() in VIDEO_EXTENSIONS


def compute_file_hash(filepath: Path) -> str:
    """Compute SHA256 hash of a file."""
    hasher = hashlib.sha256()
    with open(filepath, "rb") as f:
        # Read file in chunks to handle large files efficiently
        for chunk in iter(lambda: f.read(8192), b""):
            hasher.update(chunk)
    return hasher.hexdigest()


def validate_coco_format(annotation_file: Path) -> bool:
    """Validate COCO JSON format."""
    try:
        COCO(str(annotation_file))
        print(f"✓ COCO file is valid: {annotation_file}")
        return True
    except Exception as e:
        print(f"COCO format error: {e}")
        return False


def create_coco_categories(text_prompts: List[str]) -> List[Dict[str, Any]]:
    """
    Create COCO categories from text prompts.
    Returns: List of category dictionaries
    """
    return [
        {"id": i + 1, "name": label} for i, label in enumerate(text_prompts)
    ]


def create_coco_output(
    results: List[Any],
    text_prompts: List[str],
    metadata: Dict[str, Any],
    is_normalized: bool,
) -> Dict[str, Any]:
    """Convert SAM3 results to COCO format."""
    coco_output = {
        "info": metadata,
        "images": [],
        "annotations": [],
        "categories": create_coco_categories(text_prompts),
    }

    annotation_id = 1

    for image_idx, result in enumerate(results):
        if result.masks is None:
            continue

        height, width = result.orig_shape
        image_id = image_idx + 1
        filename = Path(result.path).name

        # Add image information
        coco_output["images"].append(
            {
                "id": image_id,
                "file_name": filename,
                "width": width,
                "height": height,
            }
        )

        polygons = result.masks.xyn if is_normalized else result.masks.xy
        boxes = result.boxes.xyxyn if is_normalized else result.boxes.xyxy
        track_ids = (
            result.boxes.id.int().tolist()
            if result.boxes.id is not None
            else [None] * len(result.boxes.cls)
        )

        for polygon, bbox, class_id, track_id in zip(
            polygons, boxes, result.boxes.cls, track_ids
        ):
            # Flatten polygon coordinates
            polygon_flat = polygon.flatten().tolist()

            # Extract bounding box coordinates (normalized)
            x1, y1, x2, y2 = bbox[:4].tolist()
            bbox_w = x2 - x1
            bbox_h = y2 - y1
            # Calculate area using contour
            area = float(cv2.contourArea(polygon.astype(np.float32)))

            coco_output["annotations"].append(
                {
                    "id": annotation_id,
                    "image_id": image_id,
                    "category_id": int(class_id) + 1,
                    "track_id": track_id,
                    "segmentation": [polygon_flat],
                    "area": area,
                    "bbox": [x1, y1, bbox_w, bbox_h],
                    "iscrowd": 0,
                }
            )
            annotation_id += 1

    return coco_output


def create_yolo_bbox_annotation(box: np.ndarray, class_id: int) -> str:
    """Create YOLO bounding box annotation line."""
    x1, y1, x2, y2 = box[:4].tolist()

    # Convert to YOLO format (center_x, center_y, width, height)
    x_center = (x1 + x2) / 2
    y_center = (y1 + y2) / 2
    bbox_width = x2 - x1
    bbox_height = y2 - y1

    return (
        f"{class_id} {x_center:.6f} "
        f"{y_center:.6f} {bbox_width:.6f} "
        f"{bbox_height:.6f}"
    )


def create_yolo_seg_annotation(polygon: np.ndarray, class_id: int) -> str:
    """Create YOLO segmentation annotation line."""
    # Flatten polygon coordinates
    flattened = [f"{coord:.6f}" for point in polygon for coord in point]
    return f"{class_id} " + " ".join(flattened)


def create_yolo_output(
    annotation_type: str,
    results: List[Any],
    output_dir: Path,
    is_normalized: bool,
) -> None:
    """Export annotations in YOLO format for images."""
    # Create subdirectories for images and labels
    images_dir = output_dir / "images"
    labels_dir = output_dir / "labels"
    images_dir.mkdir(exist_ok=True, parents=True)
    labels_dir.mkdir(exist_ok=True, parents=True)

    for result in results:
        # Generate output filename based on source image
        image_name = Path(result.path).stem

        # Copy image to images directory
        image_src = Path(result.path)
        image_dst = images_dir / f"{image_name}{image_src.suffix}"

        shutil.copy2(image_src, image_dst)

        # Create label file path
        output_path = labels_dir / f"{image_name}.txt"

        lines = []

        boxes = result.boxes.xyxyn if is_normalized else result.boxes.xyxy
        # Process each detection
        for i, (box, class_id) in enumerate(zip(boxes, result.boxes.cls)):
            class_id = int(class_id)

            if annotation_type == "bbox":
                line = create_yolo_bbox_annotation(box, class_id)
            else:  # segmentation
                masks = result.masks.xyn if is_normalized else result.masks.xy
                line = create_yolo_seg_annotation(masks[i], class_id)

            lines.append(line)

        # Write annotations to file
        with open(output_path, "w") as f:
            f.write("\n".join(lines))

    print(f"✓ Created {len(results)} images and labels in {output_dir}")


@dataclass
class FrameRecord:
    """What the exporters need from one annotated video frame.

    A Results object owns the decoded frame (H x W x 3) and every instance
    mask upsampled to the frame size (N x H x W bool), so collecting them for a
    whole video costs gigabytes: 1080p with ten masks is several hundred MB per
    frame, and the default stride of 5 on a five minute clip would need tens of
    GB. The exporters read only coordinates, class ids, track ids and the frame
    shape, a few kB per frame, so each result is projected into this record as
    soon as it arrives and then dropped.
    """

    # 0-based index of the frame in the source video, offset + n * stride
    # (see vid_stride_offset for the offset)
    frame_index: int
    frame_stem: str
    height: int
    width: int
    polygons: List[np.ndarray]
    boxes: List[np.ndarray]
    class_ids: List[int]
    track_ids: List[Any]

    @property
    def image_name(self) -> str:
        """Name of the frame image inside the directories that get a copy."""
        return f"{self.frame_stem}.jpg"


def frame_record(
    result: Any, frame_index: int, video_name: str, is_normalized: bool
) -> FrameRecord:
    """Project a video Results object into a FrameRecord."""
    height, width = result.orig_shape

    masks = result.masks
    if masks is None:
        polygons = []
    else:
        polygons = masks.xyn if is_normalized else masks.xy
    boxes = result.boxes.xyxyn if is_normalized else result.boxes.xyxy
    ids = result.boxes.id

    return FrameRecord(
        frame_index=frame_index,
        frame_stem=f"{video_name}_frame_{frame_index:06d}",
        height=height,
        width=width,
        # masks.xy/xyn are numpy arrays built from a temporary copy of the mask
        # tensor, and the boxes are a handful of floats, so neither keeps the
        # dense per-instance masks (or the frame) alive.
        polygons=list(polygons),
        boxes=list(boxes),
        class_ids=[int(class_id) for class_id in result.boxes.cls],
        track_ids=(
            [int(track_id) for track_id in ids]
            if ids is not None
            else [None] * len(boxes)
        ),
    )


def frame_output_directories(
    outdir: Path,
    want_coco: bool,
    output_frames: str,
    yolo_formats: List[str],
) -> List[Path]:
    """Directories that receive a copy of every sampled frame.

    The COCO document refers to its frame images by file name, and a YOLO
    dataset needs the images next to the labels, so both are written while the
    pixels are still in hand rather than by decoding the video again.
    """
    directories = []
    if want_coco:
        directories.append(outdir / "frames")
    if output_frames in ("raw", "both"):
        directories.append(outdir / "frames_raw")
    directories.extend(
        outdir / f"yolo_{annotation_type}" / "images"
        for annotation_type in yolo_formats
    )

    for directory in directories:
        directory.mkdir(parents=True, exist_ok=True)

    return directories


def vid_stride_offset(stride: int) -> int:
    """Source-video index of the first frame ultralytics samples.

    Releases disagree about where sampling starts: the loader in ultralytics
    8.4.33 grabs `stride` frames and then retrieves the last one, so it
    samples stride - 1, 2 * stride - 1, ..., while later releases retrieve
    first and skip afterwards, sampling 0, stride, 2 * stride, ... (see
    LoadImagesAndVideos.__next__). A synthetic video whose frames carry their
    own index tells the installed sampler apart in a few milliseconds, which
    keeps frame_index the real position in the source video either way.
    """
    if stride <= 1:
        return 0

    with tempfile.TemporaryDirectory() as tmpdir:
        probe = Path(tmpdir) / "stride_probe.avi"
        writer = cv2.VideoWriter(
            str(probe),
            cv2.VideoWriter_fourcc(*"MJPG"),
            PROBE_FPS,
            (PROBE_SIZE, PROBE_SIZE),
        )
        if not writer.isOpened():
            print("Warning: cannot write the stride probe, numbering from 0")
            return 0

        for index in range(stride + 1):
            writer.write(np.full((PROBE_SIZE, PROBE_SIZE, 3), index, np.uint8))
        writer.release()

        loader = LoadImagesAndVideos(probe, vid_stride=stride)
        try:
            _, images, _ = next(iter(loader))
        except StopIteration:
            print("Warning: the stride probe gave no frame, numbering from 0")
            return 0
        finally:
            if getattr(loader, "cap", None) is not None:
                loader.cap.release()

    # MJPG is lossy, so the flat frame value is only approximately exact
    return int(round(float(np.asarray(images[0]).reshape(-1)[0])))


def predict_video_frames(
    predictor: Any,
    video_path: str,
    text_prompts: List[str],
    stride: int,
    raw_dirs: List[Path],
    annotated_dir: Optional[Path],
    show_bbox: bool,
    is_normalized: bool,
) -> List[FrameRecord]:
    """Predict a video frame by frame and write the per-frame exports.

    The predictor is asked to stream: with stream=True it yields one Results
    per sampled frame and keeps none of them, instead of returning a list of
    every result once the video is done (ultralytics warns about exactly that,
    see STREAM_WARNING). Peak memory is then one frame rather than the whole
    video, so the frames are exported here, while their pixels are available.

    ultralytics samples the source frames offset, offset + stride, ... where
    the offset depends on the release (see vid_stride_offset), and does not
    expose the index on the Results object, so it is counted here:
    frame_index is the 0-based index of the frame in the source video, not the
    ordinal of the sampled frame.
    """
    video_name = Path(video_path).stem
    if annotated_dir is not None:
        annotated_dir.mkdir(parents=True, exist_ok=True)

    offset = vid_stride_offset(stride)
    print(f"Processing video frames (stride={stride})...")
    print(f"Frame numbering: the first sampled frame is source frame {offset}")

    records: List[FrameRecord] = []
    for result in predictor(source=video_path, text=text_prompts, stream=True):
        record = frame_record(
            result,
            offset + len(records) * stride,
            video_name,
            is_normalized,
        )

        # orig_img is the frame the annotations were computed on, so writing it
        # here also removes the drift a second decode of the video introduced
        for directory in raw_dirs:
            cv2.imwrite(str(directory / record.image_name), result.orig_img)

        if annotated_dir is not None:
            annotated = result.plot(boxes=show_bbox)
            cv2.imwrite(str(annotated_dir / record.image_name), annotated)

        records.append(record)
        if len(records) % 10 == 0:
            print(f"  Processed {len(records)} frames...")

    print(f"✓ Processed {len(records)} frames")
    return records


def create_coco_video_frames_output(
    records: List[FrameRecord],
    text_prompts: List[str],
    metadata: Dict[str, Any],
) -> Dict[str, Any]:
    """Convert the streamed video frames to COCO, one image entry per frame."""
    coco_output = {
        "info": metadata,
        "images": [],
        "annotations": [],
        "categories": create_coco_categories(text_prompts),
    }

    annotation_id = 1
    for image_id, record in enumerate(records, start=1):
        coco_output["images"].append(
            {
                "id": image_id,
                "file_name": record.image_name,
                "width": record.width,
                "height": record.height,
                "frame_index": record.frame_index,
            }
        )

        for polygon, bbox, class_id, track_id in zip(
            record.polygons, record.boxes, record.class_ids, record.track_ids
        ):
            x1, y1, x2, y2 = bbox[:4].tolist()
            coco_output["annotations"].append(
                {
                    "id": annotation_id,
                    "image_id": image_id,
                    "category_id": class_id + 1,
                    "track_id": track_id,
                    "segmentation": [polygon.flatten().tolist()],
                    "area": float(cv2.contourArea(polygon.astype(np.float32))),
                    "bbox": [x1, y1, x2 - x1, y2 - y1],
                    "iscrowd": 0,
                }
            )
            annotation_id += 1

    print(f"✓ Built COCO annotations for {len(records)} frames")
    return coco_output


def create_yolo_video_output(
    annotation_type: str,
    records: List[FrameRecord],
    output_dir: Path,
) -> None:
    """Write one YOLO label file per sampled frame.

    The matching images are written by predict_video_frames, which is the only
    place that still holds the frame pixels.
    """
    labels_dir = output_dir / "labels"
    labels_dir.mkdir(parents=True, exist_ok=True)

    for record in records:
        lines = []

        shapes = record.boxes if annotation_type == "bbox" else record.polygons
        for shape, class_id in zip(shapes, record.class_ids):
            if annotation_type == "bbox":
                lines.append(create_yolo_bbox_annotation(shape, class_id))
            else:  # segmentation
                lines.append(create_yolo_seg_annotation(shape, class_id))

        label_path = labels_dir / f"{record.frame_stem}.txt"
        with open(label_path, "w") as f:
            f.write("\n".join(lines))

    print(f"✓ Created labels for {len(records)} frames in {output_dir}")


def create_metadata(
    text_prompts: List[str], conf_threshold: float, model_path: str
) -> Dict[str, Any]:
    """Create metadata dictionary for COCO export."""
    model_path = Path(model_path)

    return {
        "description": "SAM3 semantic segmentation export",
        "model": "sam3.pt",
        "model_sha256": (
            compute_file_hash(model_path) if model_path.exists() else "N/A"
        ),
        "prompts": text_prompts,
        "confidence_threshold": conf_threshold,
        "ultralytics_version": ultralytics.__version__,
    }


